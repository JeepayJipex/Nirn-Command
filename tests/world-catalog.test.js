const assert = require('node:assert/strict');
const catalog = require('../Magelight/NirnCommand/views/palette/world-catalog.js').create();
const row = (id, label) => ({id, label});
catalog.reset('save-a', 'world-a');
assert.ok(catalog.begin('save-a','world-a','npc',1,2));
assert.ok(catalog.append('save-a','world-a','npc',1,0,row('1','Guard')));
assert.equal(catalog.complete('save-a','world-a','npc',1),false);
assert.ok(catalog.append('save-a','world-a','npc',1,1,row('2','Guard')));
assert.ok(catalog.complete('save-a','world-a','npc',1));
assert.equal(catalog.entries('npc').length,2);
assert.ok(catalog.begin('save-a','world-a','location',1,1));
assert.equal(catalog.append('save-a','world-a','location',1,1,row('3','Whiterun')),false);
assert.equal(catalog.entries('npc').length,2);
assert.ok(catalog.append('save-a','world-a','location',1,0,row('3','Whiterun')));
assert.ok(catalog.complete('save-a','world-a','location',1));
assert.ok(catalog.begin('save-a','world-a','location',2,2));
assert.ok(catalog.append('save-a','world-a','location',2,0,row('4','Twin Site')));
assert.ok(catalog.append('save-a','world-a','location',2,1,row('5','Twin Site')));
assert.ok(catalog.complete('save-a','world-a','location',2));
assert.equal(catalog.entries('location').length,2);
assert.ok(catalog.begin('save-a','world-a','npc',2,1));
assert.equal(catalog.entries('npc').length,2);
assert.ok(catalog.begin('save-a','world-a','npc',2,1,1));
assert.equal(catalog.append('save-a','world-a','npc',2,0,row('3','Old'),0),false);
assert.ok(catalog.append('save-a','world-a','npc',2,0,row('4','New'),1));
assert.equal(catalog.complete('save-a','world-a','npc',2,0),false);
assert.ok(catalog.complete('save-a','world-a','npc',2,1));
assert.equal(catalog.begin('save-a','world-a','npc',2,1,2),'applied');
catalog.reset('save-b','world-b');
assert.equal(catalog.complete('save-a','world-a','npc',2),false);
assert.equal(catalog.entries('npc').length,0);
assert.equal(catalog.entries('location').length,0);
console.log('World catalog preserves independent atomic snapshots and rejects stale sessions.');
