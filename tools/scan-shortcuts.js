// Read one MO2 profile without changing its configuration or installed mods.
// Usage: node scan-shortcuts.js <MO2 base directory> <profile> <output.js>
const fs = require('fs');
const path = require('path');
const [base, profile, output] = process.argv.slice(2);
if (!base || !profile || !output) throw Error('Usage: node scan-shortcuts.js <MO2 base directory> <profile> <output.js>');
const lines = fs.readFileSync(path.join(base,'profiles',profile,'modlist.txt'),'utf8').split(/\r?\n/);
const files = [];
const overwrite = path.join(base,'overwrite','SKSE','Plugins','OpenAnimationReplacer.ini');
if (fs.existsSync(overwrite)) files.push({file:overwrite,source:'MO2 Overwrite'});
for (const line of lines) {
  if (!line.startsWith('+')) continue;
  const name = line.slice(1).trim();
  if (!name || name.endsWith('_separator')) continue;
  const candidate = path.join(base,'mods',name,'SKSE','Plugins','OpenAnimationReplacer.ini');
  if (fs.existsSync(candidate)) files.push({file:candidate,source:name});
}
const entries = [];
if (files.length) {
  const text = fs.readFileSync(files[0].file,'utf8');
  const ui = text.split(/^\s*\[UI\]\s*$/im)[1]?.split(/^\s*\[/m)[0] || '';
  const read = (key, fallback) => { const match = ui.match(new RegExp('^\\s*'+key+'\\s*=\\s*(\\d+)','im')); return match ? Number(match[1]) : fallback; };
  const key = read('uToggleUIKey',24), mods = read('uToggleUIKeyShift',1) + 2*read('uToggleUIKeyCtrl',0) + 4*read('uToggleUIKeyAlt',0);
  if (key > 0 && key < 256 && mods >= 0 && mods < 8) entries.push({id:'builtin:oar:menu',label:'Open Animation Replacer',kind:'Mod',action:`shortcut:${key}:${mods}`,detail:`Experimental simulated DirectInput key ${key}, modifiers ${mods}`,keywords:'oar animation',source:files[0].source,confidence:'configuration only'});
  console.log('Read OAR binding from ' + files[0].file);
  if (files.length > 1) console.log('Lower-priority configuration files ignored: ' + (files.length - 1));
} else console.log('No enabled OAR configuration found.');
fs.writeFileSync(output,'// Generated by scan-shortcuts.js. Review before use.\nwindow.NIRN_SCANNED_COMMANDS = '+JSON.stringify(entries,null,2)+';\n');
